#!/usr/bin/env bash
# labs/ctf-app/build-ctf.sh
#
# PURPOSE
#   Build the chapter 38 CTF target for labs/lab-04-ctf-silent-integrity.md.
#
#   The build produces TWO keys and, by default, signs the APK with the WRONG
#   one. That is the challenge: you are handed a build whose signature does not
#   match what the app expects, the app says nothing about it, and the vault
#   produces noise instead of a flag.
#
#   The "developer" certificate hash is compiled into the app; the "distributor"
#   key signs the file. In a real engagement you would be handed a repackaged
#   APK and would not have either key. Here you generate both, which means an
#   instructor can verify the challenge is solvable and a stuck student can
#   check their answer -- see --solution.
#
# USAGE
#   # host -- build the CHALLENGE apk (signed with the wrong key)
#   ./build-ctf.sh
#
#   # host -- build and install it
#   ./build-ctf.sh --install
#
#   # host -- build the correctly-signed reference build (SPOILER: it just
#   #         prints the flag). For instructors, or to check your answer.
#   ./build-ctf.sh --solution
#
#   # host -- remove it
#   ./build-ctf.sh --uninstall
#
#   # host -- choose where artefacts go
#   OUTDIR=/tmp/ch38ctf ./build-ctf.sh --install
#
# REQUIREMENTS
#   Android SDK build-tools (aapt2, d8, zipalign, apksigner), one platform
#   android.jar, a JDK with javac and keytool, python3, and adb to install.
#   No Gradle, no network.
#
# WHAT THIS WILL *NOT* DO FOR YOU
#   * It will NOT tell you the flag. --solution builds an APK that prints it;
#     it does not print it here, because reading it off a terminal is not the
#     exercise.
#   * It will NOT work around an OEM install restriction. If `adb install`
#     returns INSTALL_FAILED_USER_RESTRICTED, that is a device policy, not a
#     fault in the APK.
#   * It will NOT leave anything inside the repository. Everything lands under
#     $OUTDIR, including both keystores. NEITHER KEY IS EVER COMMITTED.
#
# AUTHORISED TESTING ONLY. This app is deliberately weak. It is yours.

set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
OUTDIR="${OUTDIR:-${TMPDIR:-/tmp}/ch38ctf}"
PKG="com.pentest.ch38.ctf"
PKGPATH="com/pentest/ch38/ctf"

p() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
    for c in "$HOME/Android/Sdk" "$HOME/Library/Android/sdk" "$LOCALAPPDATA/Android/Sdk"; do
        [ -d "$c" ] && SDK="$c" && break
    done
fi
[ -d "${SDK:-}" ] || { echo "error: set ANDROID_HOME to your Android SDK"; exit 2; }

BT="$(ls -d "$SDK"/build-tools/* 2>/dev/null | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/*/android.jar 2>/dev/null | sort -V | tail -1)"
[ -n "$BT" ] || { echo "error: no build-tools under $SDK"; exit 2; }
[ -n "$AJ" ] || { echo "error: no platform android.jar under $SDK"; exit 2; }

pick() { if [ -x "$BT/$1" ]; then echo "$BT/$1"; else echo "$BT/$1.bat"; fi; }
AAPT2="$(pick aapt2)"; D8="$(pick d8)"
ZIPALIGN="$(pick zipalign)"; APKSIGNER="$(pick apksigner)"
[ -x "$AAPT2" ]    || AAPT2="$BT/aapt2.exe"
[ -x "$ZIPALIGN" ] || ZIPALIGN="$BT/zipalign.exe"

mkdir -p "$OUTDIR"

# --------------------------------------------------------------------------- #
# Two keys. The app expects DEV; the challenge build is signed by DIST.
# --------------------------------------------------------------------------- #
DEV_KS="$OUTDIR/ctf-dev.ks"
DIST_KS="$OUTDIR/ctf-dist.ks"

make_key() {
    [ -f "$1" ] && return 0
    keytool -genkeypair -keystore "$(p "$1")" -storepass android -keypass android \
        -alias "$2" -dname "CN=$3,O=Android Pentesting Notes" \
        -validity 10000 -keyalg RSA -keysize 2048 >/dev/null 2>&1 \
        || { echo "error: keytool failed -- is a JDK on PATH?"; exit 2; }
}
make_key "$DEV_KS"  ctfdev  "CH38 CTF Developer"
make_key "$DIST_KS" ctfdist "CH38 CTF Distributor"

fingerprint() {
    keytool -list -v -keystore "$(p "$1")" -storepass android -alias "$2" 2>/dev/null \
        | grep -i 'SHA256:' | head -1 | sed 's/.*SHA256: *//' | tr -d ': \r' | tr 'A-F' 'a-f'
}
DEV_FP="$(fingerprint "$DEV_KS" ctfdev)"
[ ${#DEV_FP} -eq 64 ] || { echo "error: could not read developer fingerprint"; exit 2; }

# --------------------------------------------------------------------------- #
# Build
# --------------------------------------------------------------------------- #
WORK="$OUTDIR/work"
rm -rf "$WORK"
mkdir -p "$WORK/src/$PKGPATH" "$WORK/classes"
cp "$HERE"/*.java "$WORK/src/$PKGPATH/"

cat > "$WORK/src/$PKGPATH/ExpectedCert.java" <<EOF
package $PKG;

/**
 * GENERATED BY build-ctf.sh -- do not edit, do not commit.
 *
 * SHA-256 of the DER encoding of the certificate this build EXPECTS.
 * The challenge APK is signed with a DIFFERENT key. That is the point.
 */
final class ExpectedCert {
    static final String SHA256 = "$DEV_FP";
    private ExpectedCert() { }
}
EOF

"$AAPT2" link -o "$(p "$WORK/base.apk")" -I "$(p "$AJ")" \
    --manifest "$(p "$HERE/AndroidManifest.xml")" \
    --min-sdk-version 21 --target-sdk-version 33 || exit 1

javac --release 8 -nowarn -classpath "$(p "$AJ")" -d "$(p "$WORK/classes")" \
    "$WORK/src/$PKGPATH"/*.java 2>&1 | grep -vE 'obsolete|Xlint|^[0-9]+ warning|deprecat' || true

[ -f "$WORK/classes/$PKGPATH/VaultActivity.class" ] || { echo "error: javac produced no classes"; exit 1; }

classfiles=()
while IFS= read -r f; do classfiles+=("$(p "$f")"); done < <(find "$WORK/classes" -name '*.class')
"$D8" --lib "$(p "$AJ")" --min-api 21 --output "$(p "$WORK")" "${classfiles[@]}" || exit 1

( cd "$WORK" && python3 -B -c "
import zipfile, shutil
shutil.copy('base.apk','unaligned.apk')
z = zipfile.ZipFile('unaligned.apk','a', zipfile.ZIP_DEFLATED)
z.write('classes.dex','classes.dex'); z.close()
" ) || exit 1

"$ZIPALIGN" -f -p 4 "$(p "$WORK/unaligned.apk")" "$(p "$WORK/aligned.apk")" || exit 1

sign_with() {
    "$APKSIGNER" sign --ks "$(p "$1")" --ks-pass pass:android --key-pass pass:android \
        --out "$(p "$2")" "$(p "$WORK/aligned.apk")" 2>&1 | grep -v WARNING
    echo "built $2"
}

MODE="${1:-}"

case "$MODE" in
    --solution)
        sign_with "$DEV_KS" "$OUTDIR/vault-solution.apk"
        echo
        echo "This build is signed with the key the app expects, so its signature"
        echo "check passes and the vault opens. Install it ONLY to verify the"
        echo "challenge is solvable, or to check an answer you already have."
        TARGET="$OUTDIR/vault-solution.apk"
        ;;
    --uninstall)
        adb uninstall "$PKG" 2>&1 | tail -1
        exit 0
        ;;
    *)
        sign_with "$DIST_KS" "$OUTDIR/vault-challenge.apk"
        TARGET="$OUTDIR/vault-challenge.apk"
        ;;
esac

echo
echo "signature schemes:"
"$APKSIGNER" verify -v "$TARGET" 2>/dev/null | grep -E "Verified using|Number of signers" | sed 's/^/    /'

if [ "$MODE" = "--install" ] || [ "${2:-}" = "--install" ]; then
    out="$(adb install -r "$TARGET" 2>&1)"
    if echo "$out" | grep -q Success; then
        echo "installed $PKG"
        echo "  adb shell am start -n $PKG/.VaultActivity"
        echo "  adb logcat -s CH38CTF:V"
    else
        if echo "$out" | grep -q INSTALL_FAILED_UPDATE_INCOMPATIBLE; then
            echo "INSTALL_FAILED_UPDATE_INCOMPATIBLE -- a differently-signed copy is"
            echo "already installed. That refusal is itself a lesson (lab 01, part D)."
            echo "Uninstall first: adb uninstall $PKG"
        else
            echo "install failed:"; echo "$out" | head -4
        fi
    fi
fi

echo
echo "done. Everything is under $OUTDIR -- nothing was written into the repository."
